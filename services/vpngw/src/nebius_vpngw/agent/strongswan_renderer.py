def _write_secret_file(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            "w",
            encoding="utf-8",
            dir=str(path.parent),
            prefix=f"{path.name}.",
            delete=False,
        ) as tmp:
            tmp_path = Path(tmp.name)
            # codeql[py/clear-text-storage-sensitive-data] - strongSwan requires on-disk PSKs; file perms are locked to 0600.
            tmp.write(content)
        os.chmod(tmp_path, 0o600)
        os.replace(tmp_path, path)
        os.chmod(path, 0o600)
    finally:
        if tmp_path is not None and tmp_path.exists():
            tmp_path.unlink()


def _safe_runtime_file(path: Path, *, private: bool = False) -> bytes:
    with os.fdopen(os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK), "rb") as stream:
        info = os.fstat(stream.fileno())
        if (
            not stat.S_ISREG(info.st_mode)
            or info.st_uid != os.geteuid()
            or info.st_nlink != 1
            or info.st_mode & 0o022
            or private
            and stat.S_IMODE(info.st_mode) != 0o600
            or info.st_size > 1024 * 1024
        ):
            raise ValueError("unsafe runtime evidence")
        data = stream.read(1024 * 1024 + 1)
        if len(data) > 1024 * 1024:
            raise ValueError("oversized runtime evidence")
        return data


def _daemon_identity() -> dict[str, str] | None:
    budget = CURRENT.get()
    remaining = (budget.effect_deadline or budget.deadline) - time.monotonic() if budget else 3.0
    # This optional, pure observation must not enter the mutation journal or
    # poison required-effect accounting when the service manager is unavailable.
    result = bounded(
        ["systemctl", "show", "strongswan", "--property=MainPID,InvocationID,ActiveState"],
        timeout=min(3.0, remaining),
    )
    fields = dict(line.split("=", 1) for line in result.stdout.splitlines() if "=" in line)
    pid, invocation = fields.get("MainPID", ""), fields.get("InvocationID", "")
    if (
        result.returncode
        or fields.get("ActiveState") != "active"
        or not pid.isdecimal()
        or int(pid) <= 0
        or re.fullmatch(r"[0-9a-f]{32}", invocation) is None
    ):
        return None
    return {"pid": pid, "invocation": invocation}


def _daemon_uses_default_config(pid: str, root: Path) -> bool:
    # Only inspect the configuration selector; never expose process environment.
    with Path(f"/proc/{pid}/environ").open("rb") as stream:
        environment = stream.read(1024 * 1024 + 1)
    if len(environment) > 1024 * 1024:
        return False
    selectors = [
        item.split(b"=", 1)[1]
        for item in environment.split(b"\0")
        if item.startswith(b"STRONGSWAN_CONF=")
    ]
    return not selectors or selectors == [os.fsencode(root)]


def _runtime_configuration_digest(root: Path) -> str | None:
    files = [root]
    for directory, dirs, names in os.walk(STRONGSWAN_CONF_DIR.parent):
        for path in [Path(directory), *(Path(directory) / name for name in dirs)]:
            info = path.lstat()
            if (
                not stat.S_ISDIR(info.st_mode)
                or info.st_uid != os.geteuid()
                or info.st_mode & 0o022
            ):
                return None
        files.extend(Path(directory) / name for name in names if name.endswith(".conf"))
        if len(files) > 256:
            return None
    digest = hashlib.sha256()
    total = 0
    for path in sorted(files):
        data = _safe_runtime_file(path)
        total += len(data)
        if total > 8 * 1024 * 1024:
            return None
        # Support the packaged include layout only. An external/custom include
        # could affect startup without appearing in this bounded closure.
        for line in data.decode("utf-8").splitlines():
            line = line.split("#", 1)[0].strip()
            if re.search(r"\binclude\b", line) and (
                path != root
                or line not in {"include strongswan.d/*.conf", "include strongswan.d/charon/*.conf"}
            ):
                return None
        digest.update(str(path.relative_to(root.parent)).encode() + b"\0" + data + b"\0")
    return digest.hexdigest()


def _runtime_proof() -> dict[str, str] | None:
    """Optimization evidence only; unsupported configuration keeps restart behavior."""
    try:
        identity = _daemon_identity()
        root = STRONGSWAN_CONF_DIR.parent.parent / "strongswan.conf"
        if identity is None or not _daemon_uses_default_config(identity["pid"], root):
            return None
        digest = _runtime_configuration_digest(root)
        network = hashlib.sha256(
            _safe_runtime_file(NETPLAN_DIR / "99-nebius-vpngw.yaml")
        ).hexdigest()
        if digest is None or _daemon_identity() != identity:
            return None
        return {
            "schema": "nebius-vpngw/strongswan-runtime-v1",
            **identity,
            "configuration": digest,
            "network_configuration": network,
        }
    except (OSError, ValueError, subprocess.SubprocessError, OperationBlocked):
        return None


def _recorded_runtime() -> dict[str, str] | None:
    try:
        parent = RUNTIME_RECEIPT.parent.lstat()
        if (
            not stat.S_ISDIR(parent.st_mode)
            or parent.st_uid != os.geteuid()
            or parent.st_mode & 0o022
        ):
            return None
        value = json.loads(_safe_runtime_file(RUNTIME_RECEIPT, private=True))
        return value if isinstance(value, dict) else None
    except (OSError, ValueError):
        return None


def _record_runtime(proof: dict[str, str]) -> None:
    try:
        RUNTIME_RECEIPT.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        parent = RUNTIME_RECEIPT.parent.lstat()
        if (
            not stat.S_ISDIR(parent.st_mode)
            or parent.st_uid != os.geteuid()
            or parent.st_mode & 0o022
        ):
            return
        _write_secret_file(RUNTIME_RECEIPT, json.dumps(proof, sort_keys=True) + "\n")
    except OSError:
        # Optional reuse evidence is never a prerequisite for completed bootstrap.
        # A later refresh without it takes the normal restart path.
        return


def _wait_for_vici_socket(timeout_seconds: float = 15.0, interval_seconds: float = 0.5) -> bool:
    from .local_commands import CURRENT

    deadline = time.monotonic() + timeout_seconds
    budget = CURRENT.get()
    if budget is not None:
        deadline = min(deadline, budget.deadline)
    while (remaining := deadline - time.monotonic()) > 0:
        try:
            with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as probe:
                probe.settimeout(min(interval_seconds or 0.1, 0.5, remaining))
                probe.connect(str(VICI_SOCKET))
            return True
        except OSError:
            pass
        time.sleep(min(interval_seconds, max(0, deadline - time.monotonic())))
    return False


def _swanctl_content(
    tunnels: list[dict[str, Any]], secrets: list[dict[str, Any]], *, activate: bool
) -> str:
    swanctl_lines = ["# generated by nebius-vpngw-agent", "connections {"]
    for tun in tunnels:
        if tun.get("ha_cold"):
            continue
        reqid = tun["if_id"]
        if type(reqid) is not int or not 100 <= reqid < DYNAMIC_REQID_BASE:
            raise ValueError("managed IPsec policy identity is outside its reserved range")
        initiate = activate and not tun.get("responder_only", False)
        name = tun["name"]
        swanctl_lines.append(f"  {name} {{")
        swanctl_lines.append(f"    version = {tun['ike_version']}")
        swanctl_lines.append("    local_addrs = %any")
        swanctl_lines.append(f"    remote_addrs = {tun['remote_public_ip']}")
        if tun["ike_props"]:
            swanctl_lines.append(f"    proposals = {','.join(tun['ike_props'])}")
        swanctl_lines.append(f"    rekey_time = {int(tun['ike_life'])}s")
        # Preserve authenticated reauthentication overlap and native
        # INITIAL_CONTACT handling. Forced replacement can loop against a
        # peer that immediately recreates a session on DELETE.
        swanctl_lines.append("    unique = no")
        swanctl_lines.append(f"    keyingtries = {0 if initiate else 1}")
        swanctl_lines.append("    local {")
        swanctl_lines.append("      auth = psk")
        if tun["local_public_ip"]:
            swanctl_lines.append(f"      id = {tun['local_public_ip']}")
        swanctl_lines.append("    }")
        swanctl_lines.append("    remote {")
        swanctl_lines.append("      auth = psk")
        swanctl_lines.append(f"      id = {tun['remote_public_ip']}")
        swanctl_lines.append("    }")
        dpd = tun.get("dpd") or {}
        if dpd:
            swanctl_lines.append(f"    dpd_delay = {int(dpd.get('interval_seconds', 30))}s")
            swanctl_lines.append(f"    dpd_timeout = {int(dpd.get('timeout_seconds', 120))}s")
        swanctl_lines.append("    children {")
        swanctl_lines.append(f"      {name} {{")
        swanctl_lines.append(f"        local_ts = {','.join(tun['local_ts'])}")
        swanctl_lines.append(f"        remote_ts = {tun['remote_ts']}")
        if tun["esp_props"]:
            swanctl_lines.append(f"        esp_proposals = {','.join(tun['esp_props'])}")
        swanctl_lines.append(f"        rekey_time = {int(tun['esp_life'])}s")
        if "replay_window" in tun:
            swanctl_lines.append(f"        replay_window = {tun['replay_window']}")
        swanctl_lines.append("        mode = tunnel")
        # Trap acquisition and direct initiation may negotiate narrower selectors.
        # Both must retain the same local kernel template identity, including
        # authenticated rekey/reauthentication overlap for this exact tunnel.
        swanctl_lines.append(f"        reqid = {reqid}")
        swanctl_lines.append(f"        start_action = {'trap|start' if initiate else 'none'}")
        swanctl_lines.append(f"        dpd_action = {'restart' if initiate else 'clear'}")
        swanctl_lines.append(f"        close_action = {'trap' if initiate else 'none'}")
        swanctl_lines.append(f"        if_id_in = {tun['if_id']}")
        swanctl_lines.append(f"        if_id_out = {tun['if_id']}")
        swanctl_lines.append("      }")
        swanctl_lines.append("    }")
        swanctl_lines.append("  }")
    swanctl_lines.append("}")

    if secrets:
        swanctl_lines.append("secrets {")
        for idx, secret in enumerate(secrets, start=1):
            swanctl_lines.append(f"  ike-psk-{idx} {{")
            swanctl_lines.append(f"    id-1 = {secret['local_id']}")
            swanctl_lines.append(f"    id-2 = {secret['remote_id']}")
            encoded = base64.b64encode(secret["secret"].encode("utf-8")).decode("ascii")
            swanctl_lines.append(f"    secret = 0s{encoded}")
            swanctl_lines.append("  }")
        swanctl_lines.append("}")

    return "\n".join(swanctl_lines) + "\n"


def authorized_configuration(cfg: dict[str, Any]) -> ConfigurationInventory:
    """Prove the loader's private file is exactly the currently eligible policy.

    The caller owns writer/ownership admission. This read grants no authority
    by itself, performs no rendering effects, and never includes secrets in errors.
    """
    tunnels, secrets, _ = collect_tunnel_state(cfg, log=lambda _message: None)
    expected = _swanctl_content(tunnels, secrets, activate=True).encode("utf-8")
    try:
        descriptor = os.open(SWANCTL_CONF, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
        with os.fdopen(descriptor, "rb") as stream:
            info = os.fstat(stream.fileno())
            if (
                not stat.S_ISREG(info.st_mode)
                or info.st_uid != os.geteuid()
                or stat.S_IMODE(info.st_mode) != 0o600
                or info.st_nlink != 1
                or info.st_size > 8 * 1024 * 1024
                or stream.read(8 * 1024 * 1024 + 1) != expected
            ):
                raise RuntimeError("current IPsec loader policy is unproven")
    except OSError:
        raise RuntimeError("current IPsec loader policy is unavailable") from None
    return ConfigurationInventory(
        frozenset(t["name"] for t in tunnels if not t.get("ha_cold")),
        frozenset(f"ike-psk-{index}" for index in range(1, len(secrets) + 1)),
    )


class StrongSwanRenderer:
    def _collect_tunnel_state(
        self, cfg: dict[str, Any]
    ) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]]]:
        return collect_tunnel_state(cfg)

    def build_interface_endpoints(self, cfg: dict[str, Any]) -> list[dict]:
        _, _, interface_endpoints = self._collect_tunnel_state(cfg)
        return interface_endpoints

    def render_and_apply(
        self,
        cfg: dict[str, Any],
        *,
        activate: bool = True,
        rendered_files: dict[Path, str | None] | None = None,
    ) -> list[dict[str, Any]]:
        """Render strongSwan config based on resolved per-VM YAML.

        Uses swanctl (VICI) to load per-tunnel connections with if_id_in/out for deterministic
        XFRM binding. The product owns configuration loading for charon-systemd.
        Supports IKEv1/IKEv2, configurable crypto proposals, DPD, and both BGP and static routing
        using XFRM interfaces.
        """
        preview = rendered_files is not None
        previous_runtime = _runtime_proof() if activate and not preview else None
        reusable_runtime = bool(
            cfg.get("_ha_static_passive") is True
            and previous_runtime is not None
            and _recorded_runtime() == previous_runtime
        )

        def write(path: Path, content: str) -> None:
            if rendered_files is not None:
                rendered_files[path] = content
            else:
                path.write_text(content, encoding="utf-8")

        tunnels, secrets, interface_endpoints = self._collect_tunnel_state(cfg)

        # Write strongSwan plugin configuration based on mode
        if not preview:
            STRONGSWAN_CONF_DIR.mkdir(parents=True, exist_ok=True)

        runtime_conf = f"""# generated by nebius-vpngw-agent
charon {{
  reqid_base = {DYNAMIC_REQID_BASE}
  install_routes = no
  routing_table = 0
  keep_alive = 20s
  retransmit_timeout = 1.0
  retransmit_base = 1.5
  retransmit_tries = 5
  retransmit_jitter = 10
  retransmit_limit = 0
  plugins {{
    kernel-netlink {{
      install_routes_xfrmi = no
    }}
  }}
}}
"""
        write(STRONGSWAN_CONF_DIR.parent / "nebius-vpngw.conf", runtime_conf)

        for name, legacy_content in _LEGACY_RUNTIME_FILES.items():
            path = STRONGSWAN_CONF_DIR / name
            if path.exists() and path.read_text(encoding="utf-8") == legacy_content:
                if rendered_files is not None:
                    rendered_files[path] = None
                else:
                    path.unlink()

        # XFRM interfaces are kernel/iproute2 objects linked to CHILD_SAs by
        # if_id_in/out.  There is no charon xfrm_if plugin.  Remove only the
        # exact legacy file written by older nebius-vpngw releases so upgraded
        # gateways stop requesting a nonexistent plugin without touching a
        # caller-owned file at the same path.
        xfrm_conf_path = STRONGSWAN_CONF_DIR / "xfrm_if.conf"
        if (
            xfrm_conf_path.exists()
            and xfrm_conf_path.read_text(encoding="utf-8") == _LEGACY_MANAGED_XFRM_IF_CONF
        ):
            if rendered_files is not None:
                rendered_files[xfrm_conf_path] = None
            else:
                xfrm_conf_path.unlink()
            print(f"[StrongSwan] Removed obsolete managed {xfrm_conf_path}")

        # This product implements VM-level HA itself and must not activate
        # strongSwan's unrelated ClusterIP/state-synchronization HA plugin.
        # Ubuntu enables that plugin by default even without local/remote sync
        # addresses, which produces a warning on every daemon start.
        ha_conf = """# generated by nebius-vpngw-agent
ha {
  load = no
}
"""
        ha_conf_path = STRONGSWAN_CONF_DIR / "zz-nebius-vpngw-ha.conf"
        write(ha_conf_path, ha_conf)
        print(f"[StrongSwan] Wrote {ha_conf_path} (disabled unused HA plugin)")

        # Disable VTI plugin if present
        vti_conf_path = STRONGSWAN_CONF_DIR / "vti.conf"
        if vti_conf_path.exists():
            vti_conf = """# generated by nebius-vpngw-agent
vti {
  load = no
}
"""
            write(vti_conf_path, vti_conf)
            print(f"[StrongSwan] Wrote {vti_conf_path} (disabled vti plugin)")

        # Write netplan override to disable IPv4 link-local addressing on eth0
        # This prevents DHCP from injecting the broad 169.254.0.0/16 route
        # SAFE: Uses link-local: [ipv6] instead of use-routes: false
        netplan_override_text = """# generated by nebius-vpngw-agent
# Disable IPv4 link-local (APIPA 169.254/16) to prevent conflicts with VPN inner IPs
# This is SAFE - it does NOT block DHCP routes (default gateway, DNS, etc.)
network:
  version: 2
  ethernets:
    eth0:
      dhcp4: true
      dhcp4-overrides:
        use-dns: true
        use-routes: true
      link-local: [ ipv6 ]
"""
        netplan_dir = NETPLAN_DIR
        if not preview:
            netplan_dir.mkdir(parents=True, exist_ok=True)
        netplan_override = netplan_dir / "99-nebius-vpngw.yaml"
        preserve_network = bool(
            reusable_runtime
            and previous_runtime is not None
            and previous_runtime["network_configuration"]
            == hashlib.sha256(netplan_override_text.encode()).hexdigest()
        )
        write(netplan_override, netplan_override_text)
        print(f"[StrongSwan] Wrote {netplan_override} (disabled IPv4 link-local)")

        # Apply netplan configuration
        network_applied = preserve_network
        if activate and not preview:
            from . import underlay

            if not preserve_network:
                underlay.preflight_reconfigure(cfg)
        if activate and not preview and not preserve_network:
            result = run(["netplan", "apply"], capture_output=True, text=True)
            if result.returncode == 0:
                network_applied = True
                print("[StrongSwan] ✓ Applied netplan configuration")
            else:
                print(f"[StrongSwan] ⚠ netplan apply failed: {result.stderr}")

        if activate and not preview:
            underlay.reconcile_locked(cfg, reconfigure=True)

        # Write swanctl.conf (includes secrets)
        if not preview:
            SWANCTL_CONF.parent.mkdir(parents=True, exist_ok=True)
        swanctl_content = _swanctl_content(tunnels, secrets, activate=activate)
        if rendered_files is not None:
            rendered_files[SWANCTL_CONF] = swanctl_content
        else:
            _write_secret_file(SWANCTL_CONF, swanctl_content)
        print(f"[StrongSwan] Wrote {SWANCTL_CONF} (permissions: 0600)")

        # Enable VICI plugin so swanctl can talk to charon
        vici_conf = """# generated by nebius-vpngw-agent
vici {
  load = yes
}
"""
        vici_conf_path = STRONGSWAN_CONF_DIR / "vici.conf"
        write(vici_conf_path, vici_conf)
        print(f"[StrongSwan] Wrote {vici_conf_path} (enabled vici plugin)")

        # Reload strongSwan to pick up new configs
        if not activate or preview:
            return interface_endpoints

        current_runtime = _runtime_proof()
        reuse = preserve_network and current_runtime == previous_runtime
        try:
            expected_configuration = _runtime_configuration_digest(
                STRONGSWAN_CONF_DIR.parent.parent / "strongswan.conf"
            )
        except (OSError, ValueError):
            expected_configuration = None
        if not reuse:
            try:
                restarted = run(
                    ["systemctl", "restart", "strongswan"],
                    check=False,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                    timeout=20,
                )
            except Exception as error:
                raise RuntimeError(
                    "IPsec daemon restart is unproven; policy was not loaded"
                ) from error
            if restarted.returncode != 0:
                raise RuntimeError("IPsec daemon restart failed; policy was not loaded")

        loaded_runtime = _runtime_proof()
        if reuse and loaded_runtime != previous_runtime:
            raise RuntimeError("IPsec daemon changed before passive policy reload")

        # Load swanctl connections and secrets via VICI
        try:
            load_result = None
            for attempt in range(1, 4):
                if not _wait_for_vici_socket():
                    print("[StrongSwan] WARNING: VICI socket not ready; retrying swanctl load")
                    time.sleep(1)
                    continue
                load_result = run(
                    ["swanctl", "--load-all"],
                    check=False,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                    timeout=20,
                )
                if load_result.returncode == 0:
                    break
                print(
                    f"[StrongSwan] WARNING: swanctl load failed (attempt {attempt}): "
                    f"{(load_result.stderr or '').strip()}"
                )
                time.sleep(1)

            if not load_result or load_result.returncode != 0:
                budget = CURRENT.get()
                if budget is not None:
                    budget.failures.append("swanctl_load")
                print("[StrongSwan] WARNING: swanctl load did not succeed")
        except Exception as e:
            print(f"[StrongSwan] WARNING: failed to load swanctl config: {e}")

        successful_load = load_result is not None and load_result.returncode == 0
        final_runtime = _runtime_proof()
        if reuse and (not successful_load or final_runtime != previous_runtime):
            raise RuntimeError("IPsec passive reload could not preserve its proven runtime")
        if loaded_runtime is not None and (
            final_runtime != loaded_runtime
            or (
                expected_configuration is not None
                and loaded_runtime["configuration"] != expected_configuration
            )
        ):
            # Restarting cannot make a later daemon/configuration race safe.
            # Unsupported optional probes still take the normal restart path.
            raise RuntimeError("IPsec daemon or configuration changed during policy load")
        if (
            successful_load
            and network_applied
            and loaded_runtime is not None
            and final_runtime == loaded_runtime
            and loaded_runtime["configuration"] == expected_configuration
        ):
            _record_runtime(loaded_runtime)

        # Return interface configuration for external management (XFRM device creation, routing)
        # XFRM interfaces must be created externally before/after strongSwan starts
        return interface_endpoints


NETPLAN_DIR = Path("/etc/netplan")
